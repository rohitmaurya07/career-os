/**
 * Converts a YYYY-MM-DD month start plus day offset into the deadline format
 * expected by the existing TaskItem model.
 */
function addDays(dateString: string, days: number): string {
  const date = new Date(`${dateString}T00:00:00`);
  date.setDate(date.getDate() + days);
  return date.toISOString().split('T')[0];
}

function makeTask(
  id: string,
  plan: {
    subjectId: SubjectId;
    topic: string;
    title: string;
    description: string;
    minutes: number;
    tags: string[];
  },
  deadline: string,
  createdAt: string,
  isDailyMission = true,
): TaskItem {
  return {
    id,
    subjectId: plan.subjectId,
    topic: plan.topic,
    title: plan.title,
    description: plan.description,
    estimatedMinutes: plan.minutes,
    priority: plan.minutes >= 75 ? 'High' : 'Medium',
    status: 'pending',
    deadline,
    isDailyMission,
    tags: plan.tags,
    createdAt,
  };
}

function buildInitialTasks(): TaskItem[] {
  const tasks: TaskItem[] = [];

  Object.entries(MONTH_STARTS).forEach(([monthId, monthStart]) => {
    const primaryPlans = PRIMARY_DAILY_PLANS[monthId];
    const dsaPlans = DSA_DAILY_PLANS[monthId];

    for (let day = 1; day < 28; day++) {
      const deadline = addDays(monthStart, day);
      const createdAt = new Date(`${deadline}T07:00:00`).toISOString();

      const primary = primaryPlans[day];
      const dsaTitle = dsaPlans[day];

      tasks.push(
        makeTask(
          `${monthId}_dsa_${String(day + 1).padStart(2, '0')}`,
          {
            subjectId: 'DSA',
            topic: 'Daily DSA',
            title: `DSA Day ${day + 1}: ${dsaTitle}`,
            description:
              'Solve without looking at the solution. Explain the pattern, brute force, optimal approach, edge cases and time/space complexity. If failed, schedule a 7-day re-solve.',
            minutes: dsaTitle.toLowerCase().includes('mock') ? 60 : 45,
            tags: ['DSA', 'Daily Mission', 'FAANG', 'Interview'],
          },
          deadline,
          createdAt,
        ),
        makeTask(
          `${monthId}_primary_${String(day + 1).padStart(2, '0')}`,
          {
            subjectId: primary[0] === 'Interview' ? 'Mock Interviews' : primary[0] as SubjectId,
            topic: primary[1],
            title: primary[2],
            description: primary[3],
            minutes: primary[4],
            tags: primary[5],
          },
          deadline,
          createdAt,
        ),
      );
    }
  });

  return tasks;
}

export const INITIAL_TASKS: TaskItem[] = buildInitialTasks();
