// Generate realistic GitHub-style heatmap data for the past 90 days
export function generateInitialHeatmap(): HeatmapDay[] {
  const days: HeatmapDay[] = [];
  const now = new Date();
  for (let i = 89; i >= 0; i--) {
    const d = new Date(now.getTime() - i * 86400000);
    const dateStr = d.toISOString().split('T')[0];
    // Create realistic patterns (some higher intensity, occasional rest day)
    const isWeekend = d.getDay() === 0 || d.getDay() === 6;
    const random = Math.sin(i * 0.4) * 0.5 + 0.5;
    let count = 0;
    let studyMinutes = 0;
    let level: 0 | 1 | 2 | 3 | 4 = 0;

    if (i < 18) {
      // Current unbroken streak
      count = Math.floor(random * 4) + 3;
      studyMinutes = count * 45 + Math.floor(Math.random() * 30);
      level = count >= 5 ? 4 : count >= 3 ? 3 : 2;
    } else if (i === 19) {
      // Missed 1 day in the past (rest day)
      count = 0;
      studyMinutes = 0;
      level = 0;
    } else {
      count = Math.floor(random * 5);
      studyMinutes = count * 40;
      level = count >= 4 ? 4 : count >= 3 ? 3 : count >= 1 ? (isWeekend ? 1 : 2) : 0;
    }

    days.push({
      date: dateStr,
      count,
      studyMinutes,
      level,
    });
  }
  return days;
}

